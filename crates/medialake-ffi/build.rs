fn main() {
    println!("cargo:rerun-if-changed=src/lib.rs");

    csbindgen::Builder::default()
        .input_extern_file("src/lib.rs")
        .csharp_dll_name("medialake_core_ffi")
        .csharp_namespace("MediaLake.Native")
        .csharp_class_name("NativeMethods")
        .csharp_use_function_pointer(true)
        .generate_csharp_file("../../ui/MediaLake.App/Native/NativeMethods.g.cs")
        .unwrap();

    // The C header for the Swift host (module CMediaLakeCore). Checked in, like NativeMethods.g.cs.
    let crate_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    cbindgen::Builder::new()
        .with_crate(crate_dir)
        .with_language(cbindgen::Language::C)
        .with_include_guard("MEDIALAKE_CORE_FFI_H")
        .with_header("// <auto-generated> by cbindgen from crates/medialake-ffi/src/lib.rs. DON'T CHANGE THIS DIRECTLY.")
        .with_no_includes()
        .with_sys_include("stdint.h")
        .with_sys_include("stddef.h")
        .with_parse_deps(false)
        .generate()
        .expect("cbindgen")
        .write_to_file("../../ui/MediaLake.Mac/Sources/CMediaLakeCore/include/medialake_core_ffi.h");
}
